// `text` with every fence's lines (opener through closer, or to end of text
// when unterminated) blanked, line count kept, so inline spans are read only
// from prose: an unstripped span regex pairs a fence's backticks with a real
// span's and skips it.
function stripFences(text) {
  const lines = text.split(/\r?\n/);
  for (const f of scanFences(text)) {
    const last = f.closed ? f.line + f.body.length : Math.min(lines.length, f.line + f.body.length) - 1;
    for (let i = f.line - 1; i <= last && i < lines.length; i++) lines[i] = '';
  }
  return lines;
}

// Every hit under `root`: { file, line, id, text }, file relative to root.
// fences counts the shell-labelled fences scanned; unlabelled counts the
// unlabelled fences, all of which are scanned too.
function scanRoot(root) {
  let fences = 0;
  let unlabelled = 0;
  const hits = [];
  for (const abs of walkMarkdown(root)) {
    const file = path.relative(root, abs).split(path.sep).join('/');
    const text = readText(abs);
    for (const f of shellFences(text)) {
      fences++;
      for (const id of detectShapes(f.body)) hits.push({ file, line: f.line, id, text: f.body });
    }
    for (const f of scanFences(text)) {
      if (f.lang !== '') continue;
      unlabelled++;
      const body = f.body.join('\n');
      for (const id of detectShapes(body)) {
        if (!PROSE_DETECTORS.has(id)) hits.push({ file, line: f.line, id, text: body });
      }
    }
    for (const line of malformedFences(text)) hits.push({ file, line, id: 'malformed-fence', text: '' });
    stripFences(text).forEach((l, i) => {
      for (const m of l.matchAll(/`[^`]+`/g)) {
        if (INLINE_EVAL_SUBST.test(m[0])) hits.push({ file, line: i + 1, id: 'inline-eval-subst', text: m[0] });
      }
    });
  }
  return { fences, unlabelled, hits, offenders: hits.map((h) => `${h.file}:${h.line} ${h.id}`) };
}

// Subtract the allowlist. offenders: hits no entry covers. stale: entries that
// match no hit (or more than one: the anchor is ambiguous).
function applyAllowlist(hits, allowlist) {
  const covered = new Set();
  const stale = [];
  for (const e of allowlist) {
    const matches = hits.filter((h) => h.file === e.file && h.id === e.detector && h.text.includes(e.anchor));
    if (matches.length === 1) covered.add(matches[0]);
    else stale.push(`${e.file} ${e.detector} ${JSON.stringify(e.anchor)}: matches ${matches.length} offenders (${matches.length === 0 ? 'remove this entry: its site no longer offends' : 'anchor is ambiguous, pick a distinctive line'})`);
  }
  const offenders = hits.filter((h) => !covered.has(h)).map((h) => `${h.file}:${h.line} ${h.id}`);
  return { offenders, stale, covered: covered.size };
}

// Allowlist entries that break the class rules.
function badEntries(allowlist) {
  const out = [];
  for (const e of allowlist) {
    const key = `${e.file} ${e.detector}`;
    if (e.kind === 'exempt') {
      if (!e.reason) out.push(`${key}: exempt entry without a reason`);
    } else if (e.kind === 'ratchet') {
      if (e.followUp !== FOLLOW_UP) out.push(`${key}: ratchet entry must cite FOLLOW_UP`);
      const excepted = RATCHET_ORIGINAL_EXCEPTIONS.some((x) => x.file === e.file && x.detector === e.detector);
      if (!NEW_SHAPE_IDS.has(e.detector) && !excepted) out.push(`${key}: ratchet entry under an original detector`);
    } else out.push(`${key}: unknown kind ${e.kind}`);
    if (!e.anchor) out.push(`${key}: no content anchor`);
  }
  return out;
}

function withTree(files, fn) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ct-fence-guard-'));
  try {
    for (const [rel, content] of Object.entries(files)) {
      fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
      fs.writeFileSync(path.join(root, rel), content);
    }
    return fn(root);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

